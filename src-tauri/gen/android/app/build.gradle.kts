val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Release signing config. Reads CI environment variables first (FACTORIA_*),
// then falls back to a local keystore.properties (gitignored). When neither is
// present, the release build is left unsigned (e.g. plain local debug builds).
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}
fun signingValue(envKey: String, propKey: String): String? =
    System.getenv(envKey) ?: keystoreProps.getProperty(propKey)

val signingStoreFile = signingValue("FACTORIA_KEYSTORE", "storeFile")
val hasSigning = signingStoreFile != null && file(signingStoreFile).exists()

